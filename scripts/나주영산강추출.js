function downloadJSON(text) {
    const lines = text.trim().split('\n');
    let results = [];
    
    lines.forEach(line => {
        const cols = line.trim().split(/\s+/);
        if (cols.length >= 9 && cols[4] === "완주") {
            const timeTrim = (timeStr) => timeStr ? timeStr.split('.')[0] : "";
            let gender = line.includes(" 여 ") ? "W" : "M";
            
            let name = cols[1];
            let club = cols[3];
            if (cols.length > 9 && cols[2] !== "남" && cols[2] !== "여") {
                name = cols[1] + " " + cols[2];
                club = cols[4];
            }

            results.push({
                n: name,
                b: cols[0],
                d: gender,
                s: timeTrim(cols[cols.length - 3]),
                bk: timeTrim(cols[cols.length - 2]),
                r: timeTrim(cols[cols.length - 1]),
                t: timeTrim(cols[cols.length - 4]),
                c: club,
                rty: "im",
                y: "2026"
            });
        }
    });

    // 여기서 파일 다운로드를 트리거합니다
    const jsonString = JSON.stringify(results, null, 2);
    const blob = new Blob([jsonString], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "naju_records.json"; // 저장될 파일명
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    console.log("파일 다운로드가 시작되었습니다!");
}

